"""Backend-neutral durability contracts; one bundle defines one causal commit."""
from __future__ import annotations
from dataclasses import dataclass
from typing import Any, Protocol


class TransactionMismatch(ValueError):
    """A transaction identity was reused for different requested effects."""


class CommitOutcomeUnknown(RuntimeError):
    """No further semantic progress is safe until this transaction is reconciled."""


@dataclass(frozen=True)
class CommitBundle:
    world_delta: Any
    runtime_delta: Any = None
    events: tuple[dict[str, Any], ...] = ()
    command_result: dict[str, Any] | None = None


@dataclass(frozen=True)
class CommitResult:
    revision: int
    time: str
    transaction_id: str
    first_sequence: int | None = None
    last_sequence: int | None = None
    command_result: dict[str, Any] | None = None


class AtomicCommitPort(Protocol):
    def commit(self, bundle: CommitBundle, expected_revision: int, transaction_id: str) -> CommitResult: ...
    def resolve_transaction(self, transaction_id: str) -> CommitResult | None: ...


class HistoryQueryPort(Protocol):
    """Detached records and bounded cursors; SQL/compression stay in adapters."""
    @property
    def revision(self) -> int: ...
    def head(self, revision: int | None = None): ...
    def origin(self): ...
    def boundary(self, revision): ...
    def cursor_candidates(self, time, revision_cap=None): ...
    def cursor_at(self, time, revision_cap=None, *, check_cancelled=None): ...
    def state_at(self, time=None, revision=None, *, check_cancelled=None): ...
    def runtime_at(self, revision=None): ...
    def source_identity(self): ...
    def commit_patch(self, revision): ...
    def commit_checksum(self, revision): ...
    def iter_commits(self, after=-1, through=None): ...
    def verified_anchor(self, revision): ...
    def events(self, start=0, end=None, kind=None, agent_id=None, limit=None, latest=False): ...
    def event_positions(self, kind=None): ...
    def event_range(self, first, last, kind=None): ...
    def last_event_sequence(self): ...
    def event_counts(self, after=-1, through=None): ...
    def event_count(self): ...
    def timeline_records(self, revision, *, agent=None, before=None, after=None, descending=True, limit=None): ...
    def decision_records_at(self, actor, when): ...
    def command_result(self, command_id): ...
    def command_results(self): ...
    def get_metadata(self, key, default=None): ...
    def set_cancellation(self, cancel_event): ...
    def reader_reference(self): ...
    def storage_bytes(self): ...
    def close(self): ...


class LiveStatePort(Protocol):
    """Published live projection; only the atomic adapter may change it."""
    version: int
    def read_view(self, time=None, revision=None): ...
    def read_many(self, keys): ...
    def export_snapshot(self, time=None, revision=None): ...
    def close(self): ...


class CommandJournalPort(Protocol):
    """Durable run-control bookkeeping outside an action state transition."""
    def begin_command(self, command): ...
    def finish_command(self, result, control): ...
    def command_result(self, command_id): ...
    def command_results(self): ...
    def set_metadata(self, key, value): ...
    def get_metadata(self, key, default=None): ...
    def flush(self): ...


class CheckpointPort(Protocol):
    def save(self, payload, path=None): ...
    def load(self, path=None): ...
    def export_prefix(self, destination, revision, state): ...


class PersistenceFactoryPort(Protocol):
    """Pair live/atomic/query/checkpoint adapters, including restore copying."""
    def create(self, initial, path, backend='memory'): ...
    def restore(self, path, backend='memory', initial=None): ...
    def open_history(self, path, *, read_only=True) -> HistoryQueryPort: ...
    def export_prefix(self, source, destination, revision, state): ...
