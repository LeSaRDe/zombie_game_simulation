"""Audit source pins, contract syntax and traceability; never runs the framework."""
import argparse
from collections import Counter
import hashlib
import json
from pathlib import Path

from tests.suite import ROOT, load_cases, coverage

MANIFEST = ROOT / "tests/source_manifest.json"
COVERAGE = ROOT / "tests/coverage.json"


def source_paths():
    formal = ROOT / "ontology/formal_v0.1"
    paths = [ROOT / "ontology/zombie_game_ontology_v0.1.md"]
    paths += sorted(formal.glob("*.ttl")) + sorted(formal.glob("*.owl"))
    paths += sorted((formal / "examples").glob("*.ttl"))
    paths += [formal / name for name in ("manifest.json", "coverage.json", "examples.json",
                                        "baseline-summary.json", "README.md", "COVERAGE.md")]
    paths += [ROOT / "prompts" / name for name in ("zombie_game_plans.md", "task_2_implementation_plan.md",
                                                  "task_2_action_and_validation_matrix.md")]
    # Pin the reviewed fixture authorship too, including explicit Gate/Shelter
    # arrangements; a later helper change must not silently alter the catalog.
    paths += sorted((ROOT / "tests" / "spec").glob("*.py"))
    paths += sorted((ROOT / "tests" / "architecture").glob("*.py"))
    paths += [ROOT / "tests/architecture/README.md", ROOT / "docs/DEEP_OOP_REFACTOR_PROPOSAL.md"]
    paths += [ROOT / "scripts/deep_oop_differential.py", ROOT / "scripts/verify_deep_oop.py"]
    return sorted(paths)


def fingerprints():
    return {str(p.relative_to(ROOT)): hashlib.sha256(p.read_bytes()).hexdigest() for p in source_paths()}


def audit():
    recorded = json.loads(MANIFEST.read_text())["sha256"]
    actual = fingerprints()
    changes = [p for p in sorted(recorded.keys() | actual.keys()) if recorded.get(p) != actual.get(p)]
    if changes:
        raise ValueError("Specification changed; review affected tests before refreshing pins: " + ", ".join(changes))
    cases = load_cases()
    mapped = coverage(cases)
    gaps = [f"{group}/{key}" for group, entries in mapped.items() for key, ids in entries.items() if not ids]
    if gaps:
        raise ValueError("Unmapped requirements: " + ", ".join(gaps))
    catalog = json.loads((ROOT / "ontology/formal_v0.1/manifest.json").read_text())
    actual_actions = set(catalog["actions"])
    unknown_actions = sorted({a for c in cases for a in c["actions"]} - actual_actions)
    if unknown_actions:
        raise ValueError(f"Unknown actions: {unknown_actions}")
    for action in actual_actions:
        if not any(c["id"] == f"ACT_{action}_success" for c in cases):
            raise ValueError(f"No dedicated successful action example for {action}")
    return {"schema_version": 1, "audit_status": "PASS", "framework_conformance": "NOT_RUN",
            "meaning": "Structural/source audit only. Mapping does not prove exhaustive semantic coverage.",
            "source_files": len(recorded), "case_count": len(cases),
            "assertion_count": sum(len(c["checks"]) for c in cases),
            "tiers": dict(sorted(Counter(c["tier"] for c in cases).items())),
            "mapping": mapped,
            "cases": [{k: c[k] for k in ("id", "tier", "requirements", "actions", "source", "decisions", "description")}
                      | {"assertions": len(c["checks"]),
                         "independent_postchecks": [key for key in ("snapshot_paths", "baseline_paths", "trial_checks", "policy_checks", "formal_checks", "performance_checks", "baseline_end") if key in c]}
                      for c in cases]}


def markdown_report(report):
    lines = ["# Test-suite coverage", "",
             "Generated by `python -m tests.audit_suite --write-coverage`.", "",
             f"**{report['case_count']} acceptance cases; {report['assertion_count']} explicit assertions**, plus independent snapshot, baseline, statistical and policy checks.", "",
             "**Framework conformance: NOT RUN.** This file describes authored tests; it is not a product test result.", "",
             "The complete case-to-source mapping is in [coverage.json](coverage.json). Source file bytes are pinned in [source_manifest.json](source_manifest.json).",
             "", "## Execution tiers", "", "| Tier | Cases |", "|---|---:|"]
    lines += [f"| {k} | {v} |" for k, v in report["tiers"].items()]
    for group, title in (("actions", "Action contracts"), ("invariants", "Ontology invariants"), ("gui", "GUI requirements")):
        lines += ["", f"## {title}", "", "| Requirement | Referencing cases | Example |", "|---|---:|---|"]
        for key, ids in report["mapping"][group].items():
            lines.append(f"| {key} | {len(ids)} | `{ids[0]}` |")
    lines += ["", "## Interpretation", "",
              "Each listed requirement has executable assertions. A case may test one aspect of a requirement; counts are not a percentage of semantic completeness. Boundary examples, sequences, independently checked snapshots and differential runs complement one another.", "",
              "All eight roles are exercised through their action capabilities. The formal OWL/SHACL package supplies source constraints and fixtures, but does not express every temporal/action law. This suite supplements those constraints; it does not treat a SHACL pass as proof of simulator correctness.", "",
              "D1–D9 tags identify proposed implementation choices inherited from the plan, not approvals. The adapter protocol and normalized error/GUI labels are test interfaces and can map to different production APIs without weakening semantics.", "",
              "Statistical checks use declared finite seed sets and thresholds; they do not establish perfect randomness or prove the baseline placement distribution. GUI export checks inspect artifacts and provenance; pixel/layout review remains additional release evidence. Performance limits are targets to measure on recorded hardware.", ""]
    return "\n".join(lines)


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--refresh-sources", action="store_true", help="Explicitly repin reviewed source changes")
    parser.add_argument("--write-coverage", action="store_true")
    args = parser.parse_args(argv)
    if args.refresh_sources:
        MANIFEST.write_text(json.dumps({"schema_version": 1, "sha256": fingerprints()}, indent=2) + "\n")
    try:
        report = audit()
        if args.write_coverage:
            COVERAGE.write_text(json.dumps(report, indent=2) + "\n")
            (ROOT / "tests/COVERAGE.md").write_text(markdown_report(report))
        print(f"Suite audit PASS: {report['case_count']} cases, {report['assertion_count']} assertions; "
              f"29 actions / 25 invariants / 16 GUI requirements mapped; {report['source_files']} source files pinned.")
        print("Framework conformance: NOT RUN.")
        return 0
    except (OSError, ValueError, KeyError) as exc:
        print(f"Suite audit FAIL: {exc}")
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
